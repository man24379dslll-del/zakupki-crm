export const HELP_GROUPS = [...new Set(HELP.map((s) => s.group))];

/** Разделы, доступные сотруднику с этими правами и ролью */
export function visibleHelp(perms: Set<string>, role: string) {
  return HELP.filter((s) => (!s.need || s.need.some((p) => perms.has(p))) && (!s.roles || s.roles.includes(role as "ADMIN")));
}

/** Текст раздела для поиска */
export function helpText(s: HelpSection) {
  return [s.title, ...s.body.map((b) => (typeof b === "string" ? b : "steps" in b ? b.steps.join(" ") : "list" in b ? b.list.join(" ") : "tip" in b ? b.tip : "warn" in b ? b.warn : b.alt))].join(" ");
}
